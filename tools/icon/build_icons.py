"""Build every icon the apps need from one drawing.

There is one mark - Gaurav Mishra's cat, redrawn for small sizes - and it lives in cat.svg beside this
script. Everything else is generated: the Android adaptive icon's two vector drawables, the monochrome
layer Android 13 themes use, the 512x512 PNG the Play listing needs, and the Windows .ico.

Generating rather than hand-maintaining matters here. The same mark in five files, edited by hand, is
five chances for the phone and the desktop to end up wearing slightly different faces.

    python tools/icon/build_icons.py
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
RES = ROOT / "app" / "src" / "main" / "res" / "drawable"
PLAY = ROOT / "docs" / "store"
WINDOWS = ROOT / "windows" / "packaging"

#: Windows picks the nearest size; below 32 the glasses close up, so the small ones are drawn at size
#: rather than squeezed down from 256.
ICO_SIZES = (16, 24, 32, 48, 64, 128, 256)

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/icon/build_icons.py from tools/icon/cat.svg - do not edit by hand.
     {what} -->
"""


def check_no_inherited_paint(svg: str) -> None:
    """Refuse a drawing whose shapes get their colour from a parent group.

    This parser reads one attribute set per element, by design. The first version of the drawing put
    the glasses inside <g stroke="..."> and the generated Android icon came out with no glasses at
    all - it rendered, it just had a bare-faced cat on it. Catching that here beats catching it in a
    store listing.
    """
    import re as _re
    for group in _re.findall(r"<g\b[^>]*>", svg):
        if any(f'{attr}="' in group for attr in ("fill", "stroke", "stroke-width")):
            raise SystemExit(
                f"cat.svg has paint on a group ({group.strip()}); put fill and stroke on each shape, "
                "or this script will drop those shapes from the Android icon without saying so.")


def paths_from(svg: str) -> dict:
    """The drawing's shapes, by the id or the fill they carry. A deliberately small parser: this reads
    one file we control, and a dependency for it would be a dependency the build has to carry."""
    out = {"fills": [], "strokes": []}
    for tag in re.findall(r"<(?:path|circle)\b[^>]*/>", svg):
        attrs = dict(re.findall(r'(\w[\w-]*)="([^"]*)"', tag))
        if tag.startswith("<circle"):
            cx, cy, r = (float(attrs[k]) for k in ("cx", "cy", "r"))
            # a circle as an arc pair, because vector drawables have no circle element
            attrs["d"] = (f"M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0 Z")
        if attrs.get("fill", "none") not in ("none", "") and not attrs["fill"].startswith("url("):
            out["fills"].append((attrs["d"], attrs["fill"]))
        if attrs.get("stroke", "none") not in ("none", ""):
            out["strokes"].append((attrs["d"], attrs["stroke"],
                                   attrs.get("stroke-width", "1"), attrs.get("stroke-linecap", "butt")))
    return out


def grouped(svg: str) -> str:
    """The scale-into-the-safe-zone transform, as a vector drawable group."""
    m = re.search(r'transform="translate\((\S+?),(\S+?)\) scale\((\S+?)\) translate', svg)
    if not m:
        return '<group>'
    px, py, s = m.group(1), m.group(2), m.group(3)
    return (f'<group android:scaleX="{s}" android:scaleY="{s}" '
            f'android:pivotX="{px}" android:pivotY="{py}">')


def vector(body: str, what: str) -> str:
    return (HEADER.format(what=what)
            + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
              '    android:width="108dp" android:height="108dp"\n'
              '    android:viewportWidth="108" android:viewportHeight="108">\n'
            + body + "</vector>\n")


def monochrome(svg: str) -> str:
    """The themed-icon layer: one silhouette, with the lenses knocked out.

    Android 13 draws this layer in a single colour of the system's choosing, so the colour version is
    no use here - a black cat with black glasses on a black head is a blob. What reads at a glance is
    the outline: ears, head, and two round holes where the glasses are. evenOdd makes the holes.
    """
    import re as _re
    head = _re.search(r'<path fill="#000000" d="([^"]+)"', svg).group(1)
    lenses = _re.findall(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="[\d.]+"', svg)
    holes = ""
    for cx, cy in lenses:
        cx, cy, r = float(cx), float(cy), 6.2
        holes += (f" M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0 Z")
    return ('    ' + grouped(svg) + '\n'
            '        <path android:fillColor="#FF000000" android:fillType="evenOdd"\n'
            f'            android:pathData="{" ".join(head.split())}{holes}"/>\n'
            '    </group>\n')


def foreground(svg: str, monochrome: bool = False) -> str:
    shapes = paths_from(svg)
    lines = ["    " + grouped(svg) + "\n"]
    for d, fill in shapes["fills"]:
        colour = "#FF000000" if monochrome else "#FF" + fill.lstrip("#")
        lines.append(f'        <path android:fillColor="{colour}"\n'
                     f'            android:pathData="{" ".join(d.split())}"/>\n')
    for d, stroke, width, cap in shapes["strokes"]:
        colour = "#FF000000" if monochrome else "#FF" + stroke.lstrip("#")
        cap_attr = f' android:strokeLineCap="{cap}"' if cap != "butt" else ""
        lines.append(f'        <path android:strokeColor="{colour}" android:strokeWidth="{width}"\n'
                     f'            android:fillColor="@android:color/transparent"{cap_attr}\n'
                     f'            android:pathData="{" ".join(d.split())}"/>\n')
    lines.append("    </group>\n")
    return "".join(lines)


def background(svg: str) -> str:
    stops = re.findall(r'<stop offset="([\d.]+)" stop-color="(#\w+)"/>', svg)
    inner, outer = stops[0][1], stops[-1][1]
    return ('    <path android:pathData="M0,0 L108,0 L108,108 L0,108 Z">\n'
            '        <aapt:attr name="android:fillColor">\n'
            '            <gradient android:type="radial" android:centerX="54" android:centerY="44"\n'
            '                android:gradientRadius="72">\n'
            f'                <item android:offset="0" android:color="#FF{inner.lstrip("#")}"/>\n'
            f'                <item android:offset="1" android:color="#FF{outer.lstrip("#")}"/>\n'
            '            </gradient>\n'
            '        </aapt:attr>\n'
            '    </path>\n')


def rasterise(svg: str, sizes) -> dict:
    from playwright.sync_api import sync_playwright
    frames = {}
    with sync_playwright() as pw:
        browser = pw.chromium.launch()
        page = browser.new_page()
        for size in sizes:
            page.set_viewport_size({"width": size, "height": size})
            page.set_content('<body style="margin:0">'
                             + svg.replace('width="512" height="512"', f'width="{size}" height="{size}"')
                             + "</body>")
            out = HERE / f".{size}.png"
            page.screenshot(path=str(out))
            frames[size] = out
        browser.close()
    return frames


def main() -> int:
    svg = (HERE / "cat.svg").read_text(encoding="utf-8")
    check_no_inherited_paint(svg)

    RES.mkdir(parents=True, exist_ok=True)
    (RES / "ic_launcher_foreground.xml").write_text(
        vector(foreground(svg), "The cat, scaled into the launcher mask's safe zone."), encoding="utf-8")
    (RES / "ic_launcher_monochrome.xml").write_text(
        vector(monochrome(svg),
               "A silhouette with the lenses knocked out, for Android 13's themed icons."),
        encoding="utf-8")
    (RES / "ic_launcher_background.xml").write_text(
        (HEADER.format(what="The warm ground the cat sits on.")
         + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
           '    xmlns:aapt="http://schemas.android.com/aapt"\n'
           '    android:width="108dp" android:height="108dp"\n'
           '    android:viewportWidth="108" android:viewportHeight="108">\n'
         + background(svg) + "</vector>\n"), encoding="utf-8")

    try:
        from PIL import Image
    except ImportError:
        print("Vector drawables written. Pillow and Playwright are needed for the PNG and the .ico.",
              file=sys.stderr)
        return 0

    frames = rasterise(svg, sorted({512, *ICO_SIZES}))
    PLAY.mkdir(parents=True, exist_ok=True)
    Image.open(frames[512]).convert("RGB").save(PLAY / "play-icon-512.png")   # Play wants no alpha
    ico = [Image.open(frames[s]).convert("RGBA") for s in ICO_SIZES]
    WINDOWS.mkdir(parents=True, exist_ok=True)
    ico[-1].save(WINDOWS / "app.ico", format="ICO",
                 sizes=[(f.width, f.height) for f in ico], append_images=ico[:-1])
    (WINDOWS / "icon.svg").write_text(svg, encoding="utf-8")
    for path in frames.values():
        path.unlink(missing_ok=True)

    print("written:")
    for p in (RES / "ic_launcher_foreground.xml", RES / "ic_launcher_monochrome.xml",
              RES / "ic_launcher_background.xml", PLAY / "play-icon-512.png",
              WINDOWS / "app.ico", WINDOWS / "icon.svg"):
        print("  ", p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
